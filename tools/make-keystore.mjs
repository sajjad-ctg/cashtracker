/**
 * Creates the release keystore and writes android/keystore.properties.
 *
 *   node tools/make-keystore.mjs
 *
 * The keystore is your app's identity: if you lose it you can never update the
 * app on Play again (unless you ask Google to reset the upload key).
 */
import { spawn } from 'node:child_process';
import { readdir, writeFile, mkdir, stat } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const p = (...s) => resolve(root, ...s);

function run(cmd, args, opts = {}) {
  return new Promise((res, rej) => {
    const useShell = process.platform === 'win32' && /\.(bat|cmd)$/i.test(cmd);
    const child = spawn(cmd, args, {
      cwd: opts.cwd || root,
      env: { ...process.env, ...(opts.env || {}) },
      stdio: 'inherit',
      shell: useShell
    });
    child.on('error', rej);
    child.on('close', (code) => (code === 0 ? res() : rej(new Error(`${cmd} → ${code}`))));
  });
}

const toolsDir = p('tools');
const entries = await readdir(toolsDir, { withFileTypes: true });
const jdkEntry = entries.find((e) => e.isDirectory() && e.name.startsWith('jdk'));
if (!jdkEntry) {
  console.error('✖ No JDK in tools/. Run: node tools/setup-toolchain.mjs');
  process.exit(1);
}
const jdk = p('tools', jdkEntry.name);
const keytool = resolve(jdk, 'bin', process.platform === 'win32' ? 'keytool.exe' : 'keytool');

const keystoreDir = p('android', 'keystore');
const storeFile = resolve(keystoreDir, 'cashtracker-release.jks');
const alias = 'cashtracker';
const validity = 10000;   // days (~27 years) – Google requires at least until 2033

await mkdir(keystoreDir, { recursive: true });

if (existsSync(storeFile)) {
  console.log('✔ Keystore already exists: android/keystore/cashtracker-release.jks');
  console.log('  (delete it first if you want a new one)');
} else {
  // strong random passwords
  const storePassword = randomBytes(12).toString('base64url');
  const keyPassword = storePassword;   // same as the store password, as Google recommends

  console.log('▸ generating the release keystore (valid ' + validity + ' days)');
  await run(keytool, [
    '-genkeypair',
    '-v',
    '-keystore', storeFile,
    '-alias', alias,
    '-keyalg', 'RSA',
    '-keysize', '2048',
    '-validity', String(validity),
    '-storepass', storePassword,
    '-keypass', keyPassword,
    '-dname', 'CN=Cash Tracker, OU=MSKCTG, O=MSKCTG, L=, ST=, C='
  ], { env: { JAVA_HOME: jdk, PATH: `${jdk}\\bin;${process.env.PATH}` } });

  await writeFile(
    p('android', 'keystore.properties'),
    `# generated by tools/make-keystore.mjs – keep this file secret\n` +
    `storeFile=keystore/cashtracker-release.jks\n` +
    `storePassword=${storePassword}\n` +
    `keyAlias=${alias}\n` +
    `keyPassword=${keyPassword}\n`
  );

  console.log('\n✔ Keystore created');
  console.log('  file:     android/keystore/cashtracker-release.jks');
  console.log('  alias:    ' + alias);
  console.log('  password: ' + storePassword);
  console.log('\n  ⚠  BACK THIS UP NOW. Store the .jks and the password in a password manager.');
  console.log('     Losing them means you can never publish an update to this app again.');
}

const size = (await stat(storeFile)).size;
console.log(`\n  keystore size: ${(size / 1024).toFixed(1)} KB`);
