/**
 * Builds the Android APK with a project-local toolchain (nothing is installed
 * system-wide):
 *
 *   tools/jdk21/        – Temurin JDK 21
 *   tools/android-sdk/  – Android SDK (platform 36, build-tools 36)
 *   tools/gradle-home/  – Gradle + Maven cache
 *
 * Delete the tools/ folder to reclaim the space.
 *
 *   node tools/build-apk.mjs
 */
import { spawn } from 'node:child_process';
import { readdir, readFile, writeFile, mkdir, copyFile, stat } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const p = (...s) => resolve(root, ...s);

function run(cmd, args, opts = {}) {
  return new Promise((resolveRun, reject) => {
    // .bat / .cmd need a shell on Windows; .exe must not use one (spaces in paths)
    const useShell = process.platform === 'win32' && /\.(bat|cmd)$/i.test(cmd);
    const child = spawn(cmd, args, {
      cwd: opts.cwd || root,
      env: { ...process.env, ...(opts.env || {}) },
      stdio: 'inherit',
      shell: useShell
    });
    child.on('error', reject);
    child.on('close', (code) => (code === 0 ? resolveRun() : reject(new Error(`${cmd} exited with ${code}`))));
  });
}

/* ---- locate the local JDK ---- */
const toolsDir = p('tools');
const entries = existsSync(toolsDir) ? await readdir(toolsDir, { withFileTypes: true }) : [];
const jdkEntry = entries.find((e) => e.isDirectory() && e.name.startsWith('jdk'));
if (!jdkEntry) {
  console.error('✖ No JDK found in tools/. Expected tools/jdk-21.x.y');
  process.exit(1);
}
const jdk = p('tools', jdkEntry.name);
const sdk = p('tools', 'android-sdk');

if (!existsSync(p(sdk, 'platforms', 'android-36'))) {
  console.error('✖ Android SDK platform 36 missing. Run: node tools/setup-toolchain.mjs');
  process.exit(1);
}

const env = {
  JAVA_HOME: jdk,
  ANDROID_HOME: sdk,
  ANDROID_SDK_ROOT: sdk,
  GRADLE_USER_HOME: p('tools', 'gradle-home'),
  PATH: `${jdk}\\bin;${p(sdk, 'platform-tools')};${process.env.PATH}`
};

/* ---- point Gradle at the local SDK ---- */
await writeFile(
  p('android', 'local.properties'),
  `# generated by tools/build-apk.mjs – machine specific\nsdk.dir=${sdk.replace(/\\/g, '/')}\n`
);

/* ---- the app always targets API 36 ---- */
const vars = await readFile(p('android', 'variables.gradle'), 'utf8');
const target = (vars.match(/targetSdkVersion\s*=\s*(\d+)/) || [])[1];
if (target !== '36') {
  console.error(`✖ targetSdkVersion is ${target || 'unset'} – it must stay on 36.`);
  process.exit(1);
}
const compile = (vars.match(/compileSdkVersion\s*=\s*(\d+)/) || [])[1];
if (compile !== '36') {
  console.error(`✖ compileSdkVersion is ${compile || 'unset'} – it must stay on 36.`);
  process.exit(1);
}

/* ---- 1. build the web app ---- */
console.log('\n▸ building the web app');
await run(process.execPath, [p('build.mjs')]);

/* ---- 2. sync the web assets into the native project ---- */
console.log('\n▸ syncing Capacitor');
const capCli = p('node_modules', '@capacitor', 'cli', 'bin', 'capacitor');
await run(process.execPath, [capCli, 'sync', 'android'], { env });

/* ---- 3. gradle assembleDebug ---- */
console.log('\n▸ building the APK (first run downloads Gradle + dependencies)');
await run(p('android', 'gradlew.bat'), ['assembleDebug'], { cwd: p('android'), env });

/* ---- 4. collect the APK ---- */
const apk = p('android', 'app', 'build', 'outputs', 'apk', 'debug', 'app-debug.apk');
if (!existsSync(apk)) {
  console.error('✖ APK not found at ' + apk);
  process.exit(1);
}
await mkdir(p('dist'), { recursive: true });
await copyFile(apk, p('dist', 'cashtracker.apk'));
const size = (await stat(p('dist', 'cashtracker.apk'))).size;

console.log(`\n✔ dist/cashtracker.apk  (${(size / 1024 / 1024).toFixed(2)} MB)`);
console.log('  install:  adb install -r dist/cashtracker.apk');
