/**
 * Builds the signed release artefacts:
 *   dist/cashtracker-release.apk   (for direct install / manual distribution)
 *   dist/cashtracker-release.aab   (for uploading to Google Play)
 *
 *   node tools/build-release.mjs --versionCode 2 --versionName 1.1.0
 *
 * Requires android/keystore.properties – run `node tools/make-keystore.mjs` first.
 */
import { spawn } from 'node:child_process';
import { readdir, writeFile, mkdir, copyFile, stat } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const p = (...s) => resolve(root, ...s);

function run(cmd, args, opts = {}) {
  return new Promise((res, rej) => {
    const useShell = process.platform === 'win32' && /\.(bat|cmd)$/i.test(cmd);
    const child = spawn(cmd, args, {
      cwd: opts.cwd || root,
      env: { ...process.env, ...(opts.env || {}) },
      stdio: 'inherit',
      shell: useShell
    });
    child.on('error', rej);
    child.on('close', (code) => (code === 0 ? res() : rej(new Error(`${cmd} → ${code}`))));
  });
}

/* ---- arguments ---- */
const argv = process.argv.slice(2);
function arg(name, fallback) {
  const i = argv.indexOf('--' + name);
  return i >= 0 && argv[i + 1] ? argv[i + 1] : fallback;
}
const versionCode = arg('versionCode', null);
const versionName = arg('versionName', null);

if (!existsSync(p('android', 'keystore.properties'))) {
  console.error('✖ android/keystore.properties is missing.');
  console.error('  Run:  node tools/make-keystore.mjs');
  process.exit(1);
}

/* ---- local toolchain ---- */
const entries = await readdir(p('tools'), { withFileTypes: true });
const jdkEntry = entries.find((e) => e.isDirectory() && e.name.startsWith('jdk'));
if (!jdkEntry) {
  console.error('✖ No JDK in tools/. Run: node tools/setup-toolchain.mjs');
  process.exit(1);
}
const jdk = p('tools', jdkEntry.name);
const sdk = p('tools', 'android-sdk');

const env = {
  JAVA_HOME: jdk,
  ANDROID_HOME: sdk,
  ANDROID_SDK_ROOT: sdk,
  GRADLE_USER_HOME: p('tools', 'gradle-home'),
  PATH: `${jdk}\\bin;${p(sdk, 'platform-tools')};${process.env.PATH}`
};

await writeFile(
  p('android', 'local.properties'),
  `# generated by tools/build-release.mjs – machine specific\nsdk.dir=${sdk.replace(/\\/g, '/')}\n`
);

/* ---- 1. build the web app ---- */
console.log('\n▸ building the web app');
await run(process.execPath, [p('build.mjs')]);

/* ---- 2. sync ---- */
console.log('\n▸ syncing Capacitor');
await run(process.execPath, [p('node_modules', '@capacitor', 'cli', 'bin', 'capacitor'), 'sync', 'android'], { env });

/* ---- 3. gradle: signed APK + AAB ---- */
const gradleArgs = ['assembleRelease', 'bundleRelease'];
if (versionCode) gradleArgs.push('-PversionCode=' + versionCode);
if (versionName) gradleArgs.push('-PversionName=' + versionName);

console.log('\n▸ building the signed release (APK + AAB)');
await run(p('android', 'gradlew.bat'), gradleArgs, { cwd: p('android'), env });

/* ---- 4. collect ---- */
await mkdir(p('dist'), { recursive: true });
const apk = p('android', 'app', 'build', 'outputs', 'apk', 'release', 'app-release.apk');
const aab = p('android', 'app', 'build', 'outputs', 'bundle', 'release', 'app-release.aab');

if (existsSync(apk)) await copyFile(apk, p('dist', 'cashtracker-release.apk'));
if (existsSync(aab)) await copyFile(aab, p('dist', 'cashtracker-release.aab'));

for (const f of ['dist/cashtracker-release.apk', 'dist/cashtracker-release.aab']) {
  if (existsSync(p(f))) {
    const s = await stat(p(f));
    console.log(`✔ ${f}  (${(s.size / 1024 / 1024).toFixed(2)} MB)`);
  } else {
    console.error('✖ missing ' + f);
    process.exit(1);
  }
}
console.log('\n  Play Console → Create app → upload dist/cashtracker-release.aab');
